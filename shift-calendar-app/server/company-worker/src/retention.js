const retentionDay = (ms) => new Date(ms + 9 * 60 * 60 * 1000).toISOString().slice(0, 10);

/** The columns of [r] that hold an install's hash, each with what 모두 지우기 does there. */
export const deviceColumns = (r) => Object.entries(r?.device ?? {});

/**
 * [SRV-09] 모두 지우기의 마지막 쓸기: 해시 열이 delete·contains인 표마다 이 설치의 줄을 지워요. 앞의 문장들(숫자 빼기, 채택된 것 끊기)이
 * 먼저 돌고 이것은 맨 끝이라, 보통은 0줄이고 새 표를 장부에만 적은 경우에도 빠지지 않아요. {table, s}로 돌려줘 몇 줄을 지웠는지 셀 수 있어요.
 */
export function forgetSweep(stmt, env, dev) {
  const out = [];
  for (const r of RETENTION) {
    const cols = deviceColumns(r).filter(([, a]) => a === "delete" || a === "contains");
    if (!cols.length) continue;
    const where = cols.map(([c, a]) => (a === "contains" ? `instr(${c}, ?) > 0` : `${c} = ?`)).join(" OR ");
    out.push({ table: r.table, s: stmt(env, `DELETE FROM ${r.table} WHERE ${where}`, ...cols.map(() => dev)) });
  }
  return out;
}

/** [SRV-09] 이 장부가 정하는 정기 정리 문장(매시 prune에서). */
export function retentionPrune(stmt, env, now) {
  return RETENTION.filter((r) => r.prune && typeof r.prune === "object").map((r) => {
    const p = r.prune;
    const args = [p.days ?? []].flat().map((d) => (p.day ? retentionDay(now - d * DAY) : now - d * DAY));
    return stmt(env, `DELETE FROM ${r.table} WHERE ${p.where}`, ...args);
  });
}

/** [SRV-15] How the day's backup takes [table]: skip, the cells to seal (and on which rows), and rows per read. */
export function backupRule(table) {
  // The search index's own tables (company_fts_*) and SQLite's are made again from the rows they come from.
  if (/^(sqlite_|_cf_|d1_|company_fts)/.test(table)) return { skip: true };
  const r = RETENTION_OF.get(table);
  if (!r) return { skip: false, seal: [], where: null, page: 2000 };
  const b = r.backup ?? true;
  if (b === false) return { skip: true };
  return { skip: false, seal: b.seal ?? [], where: b.where ?? null, page: b.page ?? 2000 };
}

const RETENTION_FORGET_WORDS = { delete: "지움", contains: "지움", cut: "연결만 끊음", law: "법정 기간 남음", sanction: "진행 중인 제재는 끝날 때까지" };

/** What 모두 지우기 does to [r], in the document's words. */
export function forgetWords(r) {
  const cols = deviceColumns(r);
  if (!cols.length) return "—";
  const words = [...new Set(cols.map(([, a]) => RETENTION_FORGET_WORDS[a]))];
  return words.length === 1 ? words[0] : cols.map(([c, a]) => `\`${c}\` ${RETENTION_FORGET_WORDS[a]}`).join(", ");
}

/** The day's backup of [r], in the document's words. */
export function backupWords(r) {
  const b = r.backup ?? true;
  if (b === false) return "뺌";
  if (b.seal?.length) return `넣음(${b.seal.map((c) => `\`${c}\``).join("·")} 잠금${b.where ? `, ${Object.entries(b.where).map(([c, v]) => `${c} ${v.join("·")}`).join(" ")} 줄만` : ""})`;
  return "넣음";
}

const retentionCell = (s) => String(s).replace(/\|/g, "\\|").replace(/\n/g, " ");

/** [SRV-10] docs/server-data.md의 회사 서버 표(시험이 문서와 대조, BAMNAT_WRITE_SERVER_DATA=1이면 고쳐 써요). */
export function serverDataTable() {
  return [
    "| 표 | 무엇 | 왜 | 지우는 때 | 설치와 이어짐 | 모두 지우기 | 하루 백업 |",
    "| --- | --- | --- | --- | --- | --- | --- |",
    ...RETENTION.map((r) => `| \`${r.table}\` | ${retentionCell(r.what)} | ${retentionCell(r.why)} | ${retentionCell(r.keep)} | ${retentionCell(r.link)} | ${forgetWords(r)} | ${backupWords(r)} |`),
  ].join("\n");
}
