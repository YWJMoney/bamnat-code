/** One pay work: s.from (달력 세트), s.f (기능들), s.stats (카드 순서), s.hourly, the words. */
function pay(s) {
  const feats = s.f ?? [];
  const wow = [s.lead, ...feats.map((x) => x.say)].filter(Boolean).join(" ");
  const usesGoal = feats.some((x) => x.line.when?.includes("목표 급여"));
  return tabWork("pay", {
    ...s, wow, changes: [...(s.changes ?? []), ...feats.map((x) => x.tag)],
    parts: [...(s.parts ?? []), ...feats.map((x) => x.line)],
    inputs: [...(usesGoal ? [goalInput(s.goal ?? 3000000)] : []), ...(s.inputs ?? [])].map((x, i) => ({ ...x, id: `i${i + 1}` })),
    tabExtra: [s.stats ? { kind: "cards", stats: s.stats } : null, s.hourly ? { kind: "hourly", ...s.hourly } : null].filter(Boolean),
    note: s.hourly ? "근무·급여 화면 모양과 시급 계산 방식(시급·주휴·야간 가산)을 바꿔요. 근무 기록은 그대로이고, 시급은 넣을 때 내 시급으로 고쳐요" : undefined,
  });
}
